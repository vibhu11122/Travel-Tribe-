export const COMMUNITY_TRIPS = MOCK_TRIPS.filter((t) => t.is_community)

export function getTripById(id: string): Trip | undefined {
  return MOCK_TRIPS.find((t) => t.id === id)
}

export function getTripBySlug(slug: string): Trip | undefined {
  return MOCK_TRIPS.find((t) => t.slug === slug)
}

export function getFilteredTrips(filters: {
  type?: string
  maxPrice?: number
  minDays?: number
  maxDays?: number
  destination?: string
}): Trip[] {
  return MOCK_TRIPS.filter((trip) => {
    if (filters.type && filters.type !== 'all') {
      if (trip.trip_type !== filters.type && !trip.tags.includes(filters.type)) return false
    }
    if (filters.maxPrice && trip.price > filters.maxPrice) return false
    if (filters.minDays && trip.duration_days < filters.minDays) return false
    if (filters.maxDays && trip.duration_days > filters.maxDays) return false
    if (filters.destination) {
      const dest = filters.destination.toLowerCase()
      if (!trip.destination.toLowerCase().includes(dest)) return false
    }
    return true
  })
}
